// Turns src/components/Icon.tsx (Tabler paths, JSX) into plain SVG markup for the promo pages.
// Run: node promo/lib/build-icons.mjs  → promo/lib/icons.js
import fs from 'node:fs';
const src = fs.readFileSync(new URL('../../src/components/Icon.tsx', import.meta.url), 'utf8');
const body = src.slice(src.indexOf('const paths'), src.indexOf('export function Icon'));
const out = {};
const re = /^\s{2}(\w+): \(c, w\) => (.*),\s*$/gm;
let m;
while ((m = re.exec(body))) {
  let jsx = m[2];
  jsx = jsx
    .replace(/<G\b/g, '<g').replace(/<\/G>/g, '</g>')
    .replace(/<Path\b/g, '<path')
    .replace(/stroke=\{c\}/g, 'stroke="currentColor"')
    .replace(/fill=\{c\}/g, 'fill="currentColor"')
    .replace(/strokeWidth=\{w\}/g, 'stroke-width="SW"')
    .replace(/strokeLinecap=/g, 'stroke-linecap=')
    .replace(/strokeLinejoin=/g, 'stroke-linejoin=')
    .replace(/fillRule=/g, 'fill-rule=')
    .replace(/clipRule=/g, 'clip-rule=')
    .replace(/\/>/g, '/>');
  out[m[1]] = jsx;
}
fs.writeFileSync(new URL('./icons.js', import.meta.url),
  '/* GENERATED by build-icons.mjs from src/components/Icon.tsx (Tabler Icons, MIT) */\nwindow.ICONS = ' + JSON.stringify(out, null, 0) + ';\n');
console.log(Object.keys(out).length, 'icons');
